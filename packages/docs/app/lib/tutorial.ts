export const STEP_BY_SLUG: Record<string, Step> = Object.fromEntries(STEPS.map((step) => [step.slug, step]))

/**
 * `Step 4 of 6`, counted rather than written.
 *
 * The step's own title already carries its number, which is exactly why this is derived: two places
 * saying the same number is one place that can be wrong after a step is inserted.
 */
export function stepKicker(slug: string): string {
  const at = STEPS.findIndex((step) => step.slug === slug)
  return at < 0 ? '' : `Step ${at + 1} of ${STEPS.length}`
}

/**
 * How long a step takes, in whole minutes, from the step itself.
 *
 * The design puts a time under each step's progress count, and a time somebody typed is a time that
 * is wrong the first time the step grows. So it is counted from the step.
 *
 * Not reading time — this is a tutorial, and the reader is typing and running things. Prose at 200
 * words a minute, plus three minutes for every block they have to type and watch the result of,
 * which is where a tutorial step's time actually goes. On the step the design costed, that comes
 * out at the eight minutes the design says.
 */
const READING = 200
const PER_BLOCK = 3

export function stepMinutes(slug: string): number {
  const step = STEP_BY_SLUG[slug]
  if (!step) return 0
  const markup = step.body()
  const words = markup
    .replace(/<[^>]+>/g, ' ')
    .split(/\s+/)
    .filter(Boolean).length
  const blocks = (markup.match(/<pre/g) ?? []).length
  return Math.max(2, Math.ceil(words / READING + blocks * PER_BLOCK))
}

/** `about eight minutes`, because a numeral there reads as a promise and a word reads as an estimate. */
const SPELLED = [
  'zero',
  'one',
  'two',
  'three',
  'four',
  'five',
  'six',
  'seven',
  'eight',
  'nine',
  'ten',
  'eleven',
  'twelve',
  'thirteen',
  'fourteen',
  'fifteen',
]

export function stepTime(slug: string): string {
  const minutes = stepMinutes(slug)
  return `about ${SPELLED[minutes] ?? minutes} minutes`
}

/**
 * What the reader's application looks like at the end of each step.
 *
 * The design puts this in the rail, and it earns its place: a tutorial adds a file at a time and by
 * step four the reader has six of them, with no single view of what they now have. The files a step
 * *touched* are marked, so the rail also answers "what did I just change".
 *
 * Cumulative by construction — each step names only what it adds, and the tree is the union of
 * every step up to and including this one. A step cannot forget to list a file it added earlier.
 */
const ADDS: Record<string, readonly string[]> = {
  'a-page': ['app/', 'app/routes/', 'app/routes/index.tsx'],
  'the-document': ['app/layout.tsx'],
  'a-loader': ['app/routes/index.data.ts'],
  'a-slow-region': [
    'app/fragments/',
    'app/fragments/feed.tsx',
    'app/fragments/feed/',
    'app/fragments/feed/skeleton.tsx',
  ],
  'making-it-change': ['app/intents/', 'app/intents/cart.ts'],
  'shipping-it': ['weft.config.ts'],
}

export interface TreeRow {
  path: string
  depth: number
  name: string
  /** Added by the step being read, rather than by one before it. */
  fresh: boolean
}

export function appSoFar(slug: string): TreeRow[] {
  const upTo = STEPS.findIndex((step) => step.slug === slug)
  if (upTo < 0) return []
  const seen: string[] = []
  for (const step of STEPS.slice(0, upTo + 1)) {
    for (const path of ADDS[step.slug] ?? []) if (!seen.includes(path)) seen.push(path)
  }
  const fresh = new Set(ADDS[slug] ?? [])
  return seen.toSorted().map((path) => {
    const parts = path.replace(/\/$/, '').split('/')
    return {
      path,
      depth: parts.length - 1,
      name: path.endsWith('/') ? `${parts.at(-1)}/` : (parts.at(-1) ?? path),
      fresh: fresh.has(path),
    }
  })
}

export function stepBody(slug: string): string {
  const step = STEP_BY_SLUG[slug]
  if (!step)
    return `<div class="card"><h3>No such step</h3><p><a href="/tutorial">Start at the beginning</a>.</p></div>`
  const index = STEPS.findIndex((s) => s.slug === slug)
  const previous = index > 0 ? STEPS[index - 1] : undefined
  const next = index < STEPS.length - 1 ? STEPS[index + 1] : undefined
  return (
    `<div class="goal"><p class="goal-kicker">Goal</p><p>${escapeHtml(step.goal)}</p></div>` +
    step.body() +
    `<nav class="sequence">${[
      previous ? `<a class="prev" href="/tutorial/${previous.slug}">← ${escapeHtml(previous.title)}</a>` : '',
      next ? `<a class="next" href="/tutorial/${next.slug}">${escapeHtml(next.title)} →</a>` : '',
    ]
      .filter(Boolean)
      .join('')}</nav>`
  )
}
